// Generates src/app/demo/dashboard-html.gen.ts from dashboard.html so the
// /demo route can bundle the markup instead of fs.readFileSync-ing it at
// runtime (no filesystem on Cloudflare Workers; and it must NOT move to
// public/ — the middleware demo gate would be bypassable via the direct
// asset URL). Runs via `prebuild`; the .gen.ts output is gitignored.
const fs = require("fs");
const path = require("path");

const src = path.join(__dirname, "..", "src/app/demo/dashboard.html");
const out = path.join(__dirname, "..", "src/app/demo/dashboard-html.gen.ts");
const html = fs.readFileSync(src, "utf-8");

// v9 guardrails — a half-done persona/nav migration must fail the build, not ship.
const navBlock = html.slice(html.indexOf('/* v9 nav contract'), html.indexOf('/* shared bits */'));
const stale = [
  ["Ridgeline", html.includes("Ridgeline")],
  ["Follow through in nav", /follow/.test(navBlock) && !/c\.id!=='follow'/.test(navBlock)],
  ["calmonth period", !html.includes("calmonth")],
  ["old localStorage account key", /rb_console_account'/.test(html)],
  ["USD overage", /\$0\.35/.test(html)],
];
const bad = stale.filter(([, hit]) => hit).map(([n]) => n);
if (bad.length) throw new Error(`[gen-demo-html] stale demo content: ${bad.join(", ")}`);
fs.writeFileSync(
  out,
  "// GENERATED by scripts/gen-demo-html.cjs from dashboard.html — do not edit.\n" +
    `export const DASHBOARD_HTML: string = ${JSON.stringify(html)};\n`
);
console.log(`[gen-demo-html] wrote ${out} (${html.length} chars)`);
